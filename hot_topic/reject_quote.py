#!/usr/bin/env python3

import argparse
import asyncio
import csv
import os
from pathlib import Path

from tqdm import tqdm

from .llm_utils import (
    REQUEST_CONCURRENCY,
    add_vllm_client_arguments,
    configure_server,
    request_batches,
    generate_text,
    make_openai_client,
)
from .utils import ContextExtractor, WHITE_PATT, normalize_model_name

SYSTEM_PROMPT = """
You are a helpful assistant. After any explanation, give a one-word yes or no answer on a separate line.
"""

USER_PROMPT = """
We're doing topic modeling and determining whether the following quote within the
<document> tags is relevant to the topic {Topic}.

We want you to determine whether to reject the quote.
It should be rejected if it
- Is not related to the topic
- Is a promotional message
- Is a public service announcement
- Is theme music or similar

Determine whether the content in <document> tags falls in any of those categories.
If so, answer with a single word yes. Otherwise, answer with a single word no.

{Document}
"""


def read_topic_quotes(path):
    with path.open(newline="", encoding="utf-8") as source:
        return list(csv.DictReader(source))


def messages_for_row(row, extract_quote_context):
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {
            "role": "user",
            "content": USER_PROMPT.format(
                Topic=row["topic"],
                Document=extract_quote_context(row),
            ),
        },
    ]


async def classify_row(
    client, model, row, extract_quote_context, max_new_tokens, reasoning_effort, semaphore
):
    return await generate_text(
        client,
        model,
        messages_for_row(row, extract_quote_context),
        max_new_tokens,
        reasoning_effort,
        "reject_quote",
        semaphore,
    )


def write_results(destination, normalized_name, responses, append):
    with destination.open("a" if append else "w", newline="", encoding="utf-8") as output:
        writer = csv.writer(output)
        if not append:
            writer.writerow([f"{normalized_name}--rejected", f"{normalized_name}--explanation"])
        rejected = [
            "yes" in (response.lower().splitlines()[-1].strip() if response else "")
            for response in responses
        ]
        cleaned = [WHITE_PATT.sub(" ", response).strip() for response in responses]
        writer.writerows(zip(rejected, cleaned))


def output_row_count(parser, output_path):
    try:
        with output_path.open(newline="", encoding="utf-8") as source:
            reader = csv.reader(source)
            next(reader)
            return sum(1 for _ in reader)
    except (OSError, csv.Error, StopIteration) as error:
        parser.error(f"could not read output CSV {output_path}: {error}")


async def run(args, rows, output_path, processed_count):
    total_quotes = len(rows)
    client = make_openai_client(args)
    semaphore = asyncio.Semaphore(REQUEST_CONCURRENCY)
    extract_quote_context = ContextExtractor()
    normalized_name = normalize_model_name(args.model)
    with tqdm(total=total_quotes, initial=processed_count, desc="Processing quotes") as progress:
        for batch in request_batches(rows[processed_count:], args.request_batch):
            responses = await asyncio.gather(*(
                classify_row(
                    client,
                    args.model,
                    row,
                    extract_quote_context,
                    args.max_new_tokens,
                    args.reasoning_effort,
                    semaphore,
                )
                for row in batch
            ))
            write_results(output_path, normalized_name, responses, append=True)
            progress.update(len(batch))


def main(raw_args=None):
    parser = argparse.ArgumentParser(description="Vote on whether topic quotes should be rejected")
    parser.add_argument(
        "-i", "--input", dest="inputs", nargs="+", required=True, type=Path,
        help="topic_quotes.csv files generated by gen.py",
    )
    parser.add_argument(
        "--root", default=Path("out"), type=Path,
        help="Root directory under which every --input file must be found",
    )
    parser.add_argument(
        "-o", "--output", type=Path,
        help="Output CSV path (defaults to out/{model}_votes.csv)",
    )
    parser.add_argument(
        "--resume",
        action="store_true",
        help="Resume from the number of data rows already in the output CSV",
    )
    add_vllm_client_arguments(parser)
    parser.set_defaults(request_batch=32)
    args = parser.parse_args(raw_args)
    root = args.root.resolve()
    validate_inputs(parser, root, args.inputs)
    configure_server(parser, args)
    output_path = (
        args.output.resolve()
        if args.output is not None
        else (Path("out") / f"{normalize_model_name(args.model)}_votes.csv").resolve()
    )
    rows = [row for input_path in args.inputs for row in read_topic_quotes(input_path)]
    if args.resume:
        if not output_path.is_file():
            parser.error(f"resume output does not exist: {output_path}")
        processed_count = output_row_count(parser, output_path)
    else:
        processed_count = 0
        output_path.parent.mkdir(parents=True, exist_ok=True)
        write_results(output_path, normalize_model_name(args.model), [], append=False)
    if processed_count > len(rows):
        parser.error(
            f"output contains {processed_count} rows, but inputs contain only {len(rows)} quotes"
        )
    asyncio.run(run(args, rows, output_path, processed_count))


def validate_inputs(parser, root, inputs):
    if not root.is_dir():
        parser.error(f"--root is not a directory: {root}")
    for path in inputs:
        resolved = path.resolve()
        if not resolved.is_relative_to(root):
            parser.error(f"--input file is outside --root: {path}")
        if not resolved.is_file():
            parser.error(f"--input file does not exist: {resolved}")


if __name__ == "__main__":
    main()
